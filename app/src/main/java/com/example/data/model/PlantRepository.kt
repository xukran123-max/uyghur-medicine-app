    fun searchPlants(
        query: String,
        categoryFilter: PlantCategory? = null,
        mizajFilter: MizajType? = null,
        propertyFilter: TraditionalProperty? = null
    ): List<MedicinalPlant> {
        return plantsList.filter { plant ->
            val matchesQuery = plant.matchesQuery(query)
            val matchesCategory = categoryFilter == null || plant.category == categoryFilter
            val matchesMizaj = mizajFilter == null || plant.mizajType == mizajFilter
            val matchesProperty = propertyFilter == null || when (propertyFilter) {
                TraditionalProperty.HOT -> plant.mizajType == MizajType.HOT_DRY || plant.mizajType == MizajType.HOT_MOIST
                TraditionalProperty.COLD -> plant.mizajType == MizajType.COLD_DRY || plant.mizajType == MizajType.COLD_MOIST
                TraditionalProperty.DRY -> plant.mizajType == MizajType.HOT_DRY || plant.mizajType == MizajType.COLD_DRY
                TraditionalProperty.MOIST -> plant.mizajType == MizajType.HOT_MOIST || plant.mizajType == MizajType.COLD_MOIST
            }
            matchesQuery && matchesCategory && matchesMizaj && matchesProperty
        }
    }
